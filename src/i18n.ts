export type Msg = keyof typeof ja;
export const dict: Record<Lang, Record<Msg, string>> = { ja, en };

export function t(lang: Lang, key: Msg, vars?: Record<string, string | number>): string {
  let s = dict[lang][key] ?? dict.ja[key] ?? String(key);
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  }
  return s;
}

export function useT() {
  const { lang } = useStore();
  return (key: Msg, vars?: Record<string, string | number>) => t(lang, key, vars);
}

export function trErr(lang: Lang, key: string): string {
  if (key in dict[lang]) return dict[lang][key as Msg];
  return key;
}

